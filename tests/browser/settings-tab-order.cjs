const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

async function checkSettingsTabOrder(page) {
  const artifactDir = path.resolve(__dirname, '../../../docs/artifact/evidence/settings-tab-order');
  fs.mkdirSync(artifactDir, { recursive: true });
  const tab = id => page.locator('#settings-tab-' + id);
  const order = () => page.locator('.settings-tabs [data-settings-tab]').evaluateAll(nodes => nodes.map(node => node.dataset.settingsTab));
  const selected = () => page.locator('.settings-tabs [aria-selected="true"]').getAttribute('data-settings-tab');
  const defaults = ['general', 'agents', 'providers', 'status', 'usage', 'bot', 'keyboard'];
  await page.locator('#status-settings-button').click();
  assert.deepEqual(await order(), defaults);
  await tab('usage').dragTo(tab('general'), { targetPosition: { x: 3, y: 10 } });
  const firstMove = ['usage', 'general', 'agents', 'providers', 'status', 'bot', 'keyboard'];
  assert.deepEqual(await order(), firstMove);
  assert.equal(await selected(), 'general', 'Dragging an inactive tab preserves the current panel');
  assert.equal(await page.locator('#settings-panel-general').isVisible(), true);
  assert.deepEqual(await page.evaluate(() => window.saved.settingsTabOrder), firstMove);
  assert.equal(await page.locator('#drop-overlay').isVisible(), false, 'Internal DnD is not a file attachment');
  const keyboardBox = await tab('keyboard').boundingBox();
  await tab('usage').dragTo(tab('keyboard'), { targetPosition: { x: keyboardBox.width - 3, y: 10 } });
  assert.deepEqual(await order(), ['general', 'agents', 'providers', 'status', 'bot', 'keyboard', 'usage']);
  await tab('usage').click();
  await tab('usage').press('Alt+ArrowLeft');
  assert.deepEqual(await order(), ['general', 'agents', 'providers', 'status', 'bot', 'usage', 'keyboard']);
  assert.equal(await selected(), 'usage');
  assert.equal(await tab('usage').evaluate(node => node === document.activeElement), true);
  await tab('usage').press('ArrowRight');
  assert.equal(await selected(), 'keyboard', 'Navigation follows the reordered DOM');
  await tab('keyboard').press('Home');
  assert.equal(await selected(), 'general');
  await tab('general').press('End');
  assert.equal(await selected(), 'keyboard');
  // Capability changes hide the bot tab without deleting its saved position.
  await tab('bot').evaluate(node => { node.style.display = 'none'; });
  await tab('status').click();
  await tab('status').press('ArrowRight');
  assert.equal(await selected(), 'usage');
  await tab('bot').evaluate(node => { node.style.display = ''; });
  const stable = await order();
  const transfer = await page.evaluateHandle(() => new DataTransfer());
  await tab('agents').dispatchEvent('dragstart', { dataTransfer: transfer });
  await tab('status').dispatchEvent('dragover', { dataTransfer: transfer, clientX: 0 });
  assert.equal(await page.locator('.settings-tab-drop-before').count(), 1);
  await page.locator('#status-settings').screenshot({ path: path.join(artifactDir, 'drop-indicator.png') });
  await tab('agents').dispatchEvent('dragend', { dataTransfer: transfer });
  assert.deepEqual(await order(), stable, 'Cancelling a drag does not reorder');
  assert.equal(await page.locator('.settings-tab-drop-before,.settings-tab-drop-after,.settings-tab-dragging').count(), 0);
  await tab('status').dispatchEvent('drop', { dataTransfer: transfer });
  assert.deepEqual(await order(), stable, 'A transfer without a local drag is ignored');
  await transfer.dispose();
  await page.keyboard.press('Escape');
  await page.locator('#status-settings-button').click();
  assert.deepEqual(await order(), stable, 'Reopening preserves order');
  await page.evaluate(() => sessionStorage.setItem('submission-restoration-fixture', JSON.stringify(window.saved)));
  await page.reload();
  await page.locator('#status-settings-button').click();
  assert.deepEqual(await order(), stable, 'Webview restoration preserves order');
  await page.setViewportSize({ width: 320, height: 640 });
  await tab('general').press('Alt+ArrowRight');
  assert.equal((await order())[1], 'general');
  await page.locator('#status-settings').screenshot({ path: path.join(artifactDir, 'reordered-narrow.png') });
  assert.ok(await page.locator('.settings-tabs').evaluate(node => node.scrollWidth <= node.clientWidth + 1));
  await page.evaluate(() => sessionStorage.setItem('submission-restoration-fixture', JSON.stringify({ ...window.saved, settingsTabOrder: ['usage', 'usage', 'unknown', null] })));
  await page.reload();
  await page.locator('#status-settings-button').click();
  assert.deepEqual(await order(), firstMove, 'Restoration drops unknown/duplicate IDs and appends missing tabs');
}
module.exports = { checkSettingsTabOrder };
